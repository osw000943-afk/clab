import { runTool, toolAvailable, recordToolRun } from '../tools-registry.js';
import crypto from 'node:crypto';

/**
 * OWASP ZAP DAST — passive scan prioritized. Heavy: runs only when ZAP is
 * installed AND the scan option zap=true AND heavy modules are enabled.
 */
export default {
  id: 's11',
  name: 'OWASP ZAP (DAST)',
  tools: ['zap'],
  async run(ctx) {
    const t = ctx.getTarget();
    if (!t) throw new Error('no-target');
    const opts = JSON.parse(ctx.scan.options || '{}');
    if (!opts.zap) {
      ctx.log('info', 'ZAP chưa được bật cho lượt quét này (options.zap) — bỏ qua');
      ctx.setSummary({ skipped: 'not-enabled' });
      return { summary: ctx._summary };
    }
    if (!ctx.limits.heavyModulesEnabled) {
      ctx.log('warn', 'Heavy modules bị tắt trong Settings — bỏ qua ZAP');
      ctx.setSummary({ skipped: 'heavy-disabled' });
      return { summary: ctx._summary };
    }
    if (!toolAvailable('zap')) {
      ctx.log('info', 'ZAP không có cài đặt (zap.sh) — bỏ qua');
      ctx.setSummary({ skipped: 'tool-missing' });
      return { summary: ctx._summary };
    }

    const apiKey = crypto.randomBytes(12).toString('hex');
    const port = 8090 + Math.floor(Math.random() * 9);
    const started = Date.now();
    // launch daemon
    const daemon = runTool('zap.sh', [
      '-daemon', '-host', '127.0.0.1', '-port', String(port), '-config', 'api.key=' + apiKey,
      '-config', 'api.disablekey=true', '-config', 'session.parseurl=true',
    ], { timeoutMs: 240000, maxBytes: 65536 });
    // wait for API up
    const base = 'http://127.0.0.1:' + port;
    let up = false;
    for (let i = 0; i < 30; i++) {
      await new Promise((r) => setTimeout(r, 2000));
      try {
        const r = await fetch(base + '/JSON/core/view/version/');
        if (r.ok) { up = true; break; }
      } catch { /* still starting */ }
    }
    if (!up) {
      ctx.log('error', 'ZAP daemon không khởi động được trong 60s');
      ctx.setSummary({ failed: 'daemon-start-timeout' });
      recordToolRun({ scanId: ctx.scan.id, toolId: 'zap', status: 'failed', startedAt: started, stderrExcerpt: 'daemon start timeout' });
      return { summary: ctx._summary };
    }
    const results = { alerts: [] };
    try {
      // open URL (passive records generated by spider of the single page)
      await fetch(base + '/JSON/core/action/accessUrl/?url=' + encodeURIComponent(t.url.toString()) + '&followRedirects=true');
      // bounded spider
      await fetch(base + '/JSON/spider/action/scan/?url=' + encodeURIComponent(t.url.toString()) + '&maxChildren=10');
      await new Promise((r) => setTimeout(r, 45000));
      // pull alerts
      const ar = await fetch(base + '/JSON/alerts/view/alerts/?baseFormat=riskid');
      const aj = await ar.json();
      const alerts = (aj.alerts || []).slice(0, 40);
      results.alerts = alerts.length;
      for (const a of alerts) {
        const sev = ({ 3: 'high', 2: 'medium', 1: 'low', 0: 'informational' })[Number(a.riskid)] || 'informational';
        ctx.addFinding({
          asset: a.url || t.host, stageId: 's11', tool: 'zap', severity: sev, confidence: 'medium',
          title: 'ZAP: ' + String(a.name || '').slice(0, 180),
          description: String(a.desc || '').slice(0, 1000),
          evidence: JSON.stringify({ url: a.url, param: a.param, cid: a.cid, riskid: a.riskid }).slice(0, 800),
          recommendation: String(a.solution || '').slice(0, 800) || 'Xem cảnh báo ZAP chi tiết.',
          verification: 'needs-verification',
        });
      }
      recordToolRun({ scanId: ctx.scan.id, toolId: 'zap', status: 'completed', startedAt: started });
    } finally {
      try { await fetch(base + '/JSON/core/action/shutdown/'); } catch { /* ignore */ }
      // make sure the process is gone
      setTimeout(() => { daemon && daemon.then && daemon.then(() => {}); }, 0);
    }
    ctx.setSummary(results);
    return { summary: ctx._summary };
  },
};
